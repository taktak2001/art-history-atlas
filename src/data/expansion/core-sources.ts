import type { Source } from '@/lib/schema';

const ACCESSED = '2026-07-30';

function metObject(
  id: number,
  title: string,
  supports: string,
): Source {
  return {
    id: `met-object-${id}`,
    title,
    publisher: 'The Metropolitan Museum of Art',
    url: `https://www.metmuseum.org/art/collection/search/${id}`,
    accessed: ACCESSED,
    kind: 'museum',
    reliability: 'high',
    supports,
  };
}

function aicObject(
  id: number,
  title: string,
  supports: string,
): Source {
  return {
    id: `aic-object-${id}`,
    title,
    publisher: 'Art Institute of Chicago',
    url: `https://www.artic.edu/artworks/${id}`,
    accessed: ACCESSED,
    kind: 'museum',
    reliability: 'high',
    supports,
  };
}


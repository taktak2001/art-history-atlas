import type { Source } from '@/lib/schema';

const ACCESSED = '2026-07-30';

function institutional(
  id: string,
  title: string,
  publisher: string,
  url: string,
  supports: string,
  kind: Source['kind'] = 'museum',
): Source {
  return {
    id,
    title,
    publisher,
    url,
    accessed: ACCESSED,
    kind,
    reliability: 'high',
    supports,
  };
}

function commons(id: string, title: string, fileName: string): Source {
  return institutional(
    id,
    title,
    'Wikimedia Commons — verified file page',
    `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(fileName)}`,
    `${title}の作者・年代・媒体・画像ファイル・ライセンス`,
    'archive',
  );
}

